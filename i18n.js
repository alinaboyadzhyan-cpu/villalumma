let currentLang = DEFAULT_LANG;

function detectBrowserLang() {
  const candidates = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || navigator.userLanguage || 'en'];
  const aliases = { nb: 'no', nn: 'no' }; // Norwegian Bokmål / Nynorsk both map to our single "no" dictionary
  for (const raw of candidates) {
    if (!raw) continue;
    let code = raw.slice(0, 2).toLowerCase();
    if (aliases[code]) code = aliases[code];
    if (SUPPORTED_LANGS.includes(code)) return code;
  }
  return DEFAULT_LANG;
}

function t(key, lang) {
  const dict = translations[lang] || translations[DEFAULT_LANG];
  return (dict && dict[key] !== undefined) ? dict[key] : (translations[DEFAULT_LANG][key] !== undefined ? translations[DEFAULT_LANG][key] : key);
}

function applyLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = DEFAULT_LANG;
  currentLang = lang;
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key, lang);
  });

  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    el.setAttribute('alt', t(el.getAttribute('data-i18n-alt'), lang));
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'), lang));
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'), lang));
  });

  document.querySelectorAll('[data-i18n-label]').forEach(el => {
    const val = t(el.getAttribute('data-i18n-label'), lang);
    el.setAttribute('data-label', val);
  });

  document.querySelectorAll('[data-i18n-planlabel]').forEach(el => {
    const val = t(el.getAttribute('data-i18n-planlabel'), lang);
    el.setAttribute('data-plan-label', val);
  });

  const metaDesc = document.getElementById('metaDescription');
  if (metaDesc) metaDesc.setAttribute('content', t('meta.description', lang));

  const submitBtn = document.querySelector('#enquiryForm button[type="submit"]');
  if (submitBtn && !submitBtn.disabled) {
    submitBtn.textContent = t('contact.submitBtn', lang);
  }

  if (langSelectEl) langSelectEl.value = lang;
}

let langSelectEl = null;

function initLanguageSwitcher() {
  langSelectEl = document.getElementById('langSelect');
  if (!langSelectEl) return;
  langSelectEl.innerHTML = '';
  SUPPORTED_LANGS.forEach(code => {
    const opt = document.createElement('option');
    opt.value = code;
    opt.textContent = code.toUpperCase();
    opt.title = LANG_NAMES[code];
    langSelectEl.appendChild(opt);
  });
  langSelectEl.addEventListener('change', () => applyLanguage(langSelectEl.value));
}

document.addEventListener('DOMContentLoaded', () => {
  initLanguageSwitcher();
  applyLanguage(detectBrowserLang());
});
